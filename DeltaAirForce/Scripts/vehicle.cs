function TOWMissile::onAdd(%this) 
{
	GameBase::setRechargeRate(%this, -25); // TOW lives for 4 seconds
	schedule("OutOfCable("@%this@");", 4, %this);
	schedule("$TOWDetEnable["@%this@"] = 1;", 0.5, %this);
}

