		//remoteEval(%cl, BP, "<jc><f0>TOW Missile Remotely Detonated", 4);
		bottomprint(%cl, "<jc><f0>TOW Missile Remotely Detonated", 4);
		$TOWDetEnable[%this] = 0;
	}
}

